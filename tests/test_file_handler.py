"""Unit tests for src.file_handler module."""

from pathlib import Path

from src.file_handler import (
    generate_unique_filename,
    list_saved_summaries,
    read_text_file,
    save_summary_markdown,
)


def test_generate_unique_filename_collision_avoidance(tmp_path: Path) -> None:
    """Test that existing filenames trigger numeric increment to prevent overwriting."""
    f1 = generate_unique_filename(base_name="summary", extension=".md", output_dir=tmp_path)
    f1.write_text("dummy", encoding="utf-8")

    # Second generation within same second should append counter _1
    f2 = generate_unique_filename(base_name="summary", extension=".md", output_dir=tmp_path)
    assert f2 != f1
    assert not f2.exists()


def test_save_summary_markdown_structure(tmp_path: Path) -> None:
    """Test that saved markdown contains all required metadata and sections."""
    data = {
        "title": "Quantum Computing Breakthroughs",
        "url": "https://example.com/quantum",
        "model": "gemini-3.5-flash",
        "word_count": 850,
        "total_duration_sec": 3.45,
        "tldr": "Researchers have demonstrated a fault-tolerant logical qubit.",
        "summary": "This article outlines recent quantum progress in superconducting circuits.",
        "key_takeaways": [
            "Coherence times doubled through novel materials.",
            "Error rates dropped below the fault-tolerance threshold.",
            "Commercial hardware is projected within 5 years.",
        ],
        "topics_and_keywords": ["Quantum Mechanics", "Qubits", "Superconductors"],
        "central_message": "Fault-tolerant quantum computing is moving from theory to engineering reality.",
    }

    saved_path = save_summary_markdown(data, output_dir=tmp_path)

    assert saved_path.exists()
    content = saved_path.read_text(encoding="utf-8")

    # Assert all mandatory sections
    assert "# Quantum Computing Breakthroughs" in content
    assert "https://example.com/quantum" in content
    assert "`gemini-3.5-flash`" in content
    assert "850 words" in content
    assert "3.45 seconds" in content
    assert "## TL;DR" in content
    assert "## Summary" in content
    assert "## Key Takeaways" in content
    assert "- Coherence times doubled through novel materials." in content
    assert "## Important Topics & Keywords" in content
    assert "Quantum Mechanics, Qubits, Superconductors" in content
    assert "## Central Message" in content
    assert "Generated by AI Article Summarizer" in content


def test_read_text_file_valid(tmp_path: Path) -> None:
    """Test reading utf-8 text file."""
    f = tmp_path / "article.txt"
    f.write_text("Sample article text content for reading test.", encoding="utf-8")

    text = read_text_file(f)
    assert text == "Sample article text content for reading test."


def test_list_saved_summaries(tmp_path: Path) -> None:
    """Test listing saved summaries sorted by timestamp."""
    f1 = tmp_path / "summary_20261031_100000.md"
    f2 = tmp_path / "summary_20261031_120000.md"
    f1.write_text("one", encoding="utf-8")
    f2.write_text("two", encoding="utf-8")

    summaries = list_saved_summaries(tmp_path)
    assert len(summaries) == 2
    assert all(p.suffix == ".md" for p in summaries)
